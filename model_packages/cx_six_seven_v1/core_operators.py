"""F2 compatibility wrappers around the current reference-model pure operators.

This module deliberately does not own orchestration, state writes, wall-clock
advancement, tick consumption, provider calls, or sending.  It only adapts
immutable Model SDK payloads to the existing formulas so parity can be proven
before those formulas move into the reference package.
"""
from __future__ import annotations

from collections.abc import Mapping
from typing import Any

from .continuous_root_projection import (
    CONTINUOUS_ROOT_PROJECTION_B_V1,
    project_continuous_roots,
)
from .interaction_geometry import (
    OPENING_AUTHORITY_V5,
    SCHEDULE_VECTOR_AUTHORITY_V2,
    opening_authority_receipt,
    relationship_transition,
)
from framework.model_api import ModelInvocationContext, thaw_model_data
from .semantic_projection import coerce_projection
from .root_time import ROOT_TIME_VECTOR_V2, settle_root_time_vector


def _plain_mapping(value: object, field_name: str) -> dict[str, Any]:
    if not isinstance(value, Mapping):
        raise ValueError(f"{field_name} must be a mapping")
    plain = thaw_model_data(value)
    if not isinstance(plain, dict):
        raise ValueError(f"{field_name} must be a mapping")
    return plain


def _require_payload_keys(
    payload: Mapping[str, Any], required: set[str], *, stage: str,
) -> None:
    actual = set(payload)
    if actual != required:
        missing = sorted(required - actual)
        unexpected = sorted(actual - required)
        raise ValueError(
            f"{stage} payload keys do not match contract; "
            f"missing={missing}, unexpected={unexpected}"
        )


def _identifier(value: object, field_name: str) -> str:
    normalized = str(value or "").strip()
    if not normalized:
        raise ValueError(f"{field_name} must be a non-empty identifier")
    return normalized


def _non_negative_int(value: object, field_name: str) -> int:
    if isinstance(value, bool) or not isinstance(value, int) or value < 0:
        raise ValueError(f"{field_name} must be a non-negative integer")
    return value


def _context(value: object) -> ModelInvocationContext:
    if not isinstance(value, ModelInvocationContext):
        raise ValueError("context must be ModelInvocationContext")
    return value


class CxSixSevenCoreOperatorsAdapter:
    """First F2 parity seam: event projection, time flow, and action assessment."""

    def semantic_measurement(
        self, *, payload: Mapping[str, Any], context: ModelInvocationContext,
    ) -> dict[str, Any]:
        context = _context(context)
        _require_payload_keys(
            payload,
            {"raw_measurement", "event_kind"},
            stage="semantic_measurement",
        )
        raw_measurement = thaw_model_data(payload["raw_measurement"])
        # axis_presence is generated by normalization and records which axes
        # the provider actually supplied. Re-parsing a committed projection as
        # raw input would turn the filled-in zeros into falsely supplied axes.
        if isinstance(raw_measurement, Mapping) and "axis_presence" in raw_measurement:
            raise ValueError("semantic_measurement received an already-normalized projection")
        event_kind = _identifier(payload["event_kind"], "event_kind")
        committed_kind = _identifier(
            context.metadata.get("committed_event_kind"), "committed event kind")
        if event_kind != committed_kind:
            raise ValueError("semantic_measurement event kind differs from committed event")
        measurement = coerce_projection(
            raw_measurement,
            turn_id=context.event_id,
            event_kind=event_kind,
        )
        return {
            "measurement": (
                measurement.as_record() if measurement is not None else None
            ),
        }

    def event_transition(
        self, *, payload: Mapping[str, Any], context: ModelInvocationContext,
    ) -> dict[str, Any]:
        _context(context)
        _require_payload_keys(
            payload,
            {"before", "after", "constant_binding"},
            stage="event_transition",
        )
        before = _plain_mapping(payload["before"], "before")
        after = _plain_mapping(payload["after"], "after")
        constant_binding = _plain_mapping(
            payload["constant_binding"], "constant_binding")
        transition = relationship_transition(before, after)
        projection = project_continuous_roots(
            transition=transition,
            constant_binding=constant_binding,
            params=CONTINUOUS_ROOT_PROJECTION_B_V1,
        ).to_record()
        return {
            "event_transition": transition,
            "continuous_projection": projection,
        }

    def time_transition(
        self, *, payload: Mapping[str, Any], context: ModelInvocationContext,
    ) -> dict[str, Any]:
        context = _context(context)
        _require_payload_keys(
            payload,
            {"constants", "state", "from_ms", "elapsed_ms", "constants_version"},
            stage="time_transition",
        )
        constants = _plain_mapping(payload["constants"], "constants")
        state = _plain_mapping(payload["state"], "state")
        from_ms = _non_negative_int(payload["from_ms"], "from_ms")
        elapsed_ms = _non_negative_int(payload["elapsed_ms"], "elapsed_ms")
        if context.at_ms - from_ms != elapsed_ms:
            raise ValueError("time_transition wall-clock interval does not match context")
        constants_version = _identifier(
            payload["constants_version"], "constants_version")
        transition = settle_root_time_vector(
            constants,
            state,
            elapsed_ms,
            constants_version=constants_version,
            params=ROOT_TIME_VECTOR_V2,
        )
        return {"time_transition": transition}

    def action_assessment(
        self, *, payload: Mapping[str, Any], context: ModelInvocationContext,
    ) -> dict[str, Any]:
        context = _context(context)
        event_kind = _identifier(payload.get("event_kind"), "event_kind")
        required = {
            "before", "after", "constants", "constants_version",
            "event_kind", "min_interval_ms", "max_interval_ms",
        }
        if event_kind == "tick":
            # The current reference model's F15 also requires an already
            # committed opening anchor. Its absence is an explicit fact, not
            # something to infer from a recent message or positive P3 margin.
            required.add("opening_anchor")
        _require_payload_keys(
            payload, required,
            stage="action_assessment",
        )
        if context.event_id is None:
            raise ValueError("action_assessment requires context.event_id")
        before = _plain_mapping(payload["before"], "before")
        after = _plain_mapping(payload["after"], "after")
        constants = _plain_mapping(payload["constants"], "constants")
        constants_version = _identifier(
            payload["constants_version"], "constants_version")
        committed_kind = _identifier(
            context.metadata.get("committed_event_kind"), "committed event kind")
        if event_kind != committed_kind:
            raise ValueError(
                "action_assessment event kind differs from committed event")
        min_interval_ms = _non_negative_int(
            payload["min_interval_ms"], "min_interval_ms")
        max_interval_ms = _non_negative_int(
            payload["max_interval_ms"], "max_interval_ms")
        if max_interval_ms < min_interval_ms:
            raise ValueError("max_interval_ms must be >= min_interval_ms")
        receipt = opening_authority_receipt(
            before,
            after,
            constants,
            constants_version=constants_version,
            event_kind=event_kind,
            event_id=context.event_id,
            observed_at_ms=context.at_ms,
            min_interval_ms=min_interval_ms,
            max_interval_ms=max_interval_ms,
            schedule_params=SCHEDULE_VECTOR_AUTHORITY_V2,
            opening_params=OPENING_AUTHORITY_V5,
        )
        if event_kind != "tick":
            return {"opening_authority": receipt}
        anchor = payload["opening_anchor"]
        if anchor is not None:
            anchor = _plain_mapping(anchor, "opening_anchor")
            anchor_at = _non_negative_int(anchor.get("ts"), "opening_anchor.ts")
            if anchor_at > context.at_ms:
                raise ValueError("opening_anchor is later than assessed tick")
        return {
            "opening_authority": receipt,
            "autonomous_opening": {
                "eligible": bool(anchor is not None and receipt["margin"] >= 0.0),
                "next_observation_at_ms": context.at_ms + receipt["h_next_ms"],
            },
        }
